def history(last_count=4):
    """Two fixed assistant turns: one course then four, both with notices and receipts."""
    messages = []
    for turn, evidence in enumerate([COURSES[:1], [*COURSES, *EXTRA_COURSES][:last_count]]):
        content = f"Synthetic answer {turn} with **bold**."
        messages.extend([
            {"role": "user", "content": f"Synthetic question {turn}"},
            {"role": "assistant", "content": content, "evidence": copy.deepcopy(evidence),
             "matched_via": "hybrid", "notices": ["program_schedule_unverified"],
             "feedback": {"answer_id": f"{turn:032x}", "feedback_token": "s" * 43,
                          "answer_sha256": hashlib.sha256(content.encode()).hexdigest()}},
        ])
    return messages


def layout_snapshot(app, forwarded):
    """Ordered trees plus stable delta metadata, excluding random widget IDs/script hashes."""
    metadata = {}
    for message in forwarded:
        if "delta" in message:
            path = tuple(message.get("metadata", {}).get("delta_path", []))
            metadata[path] = message["delta"]
    rows = []

    def walk(node, path):
        proto = MessageToDict(node.proto, preserving_proto_field_name=True) if node.proto is not None else {}
        widget_id = proto.pop("id", None)
        if widget_id:
            key = widget_id.split("-", 2)[-1]
            if key != "None":
                proto["key"] = key
        # Streamlit uses an autogenerated script path as the form identity; no forms in these blocks.
        proto.pop("form_id", None)
        delta = metadata.get(tuple(path), {})
        width = delta.get("new_element", {}).get("width_config")
        rows.append({"path": path, "type": node.type, "proto": proto, **({"width": width} if width else {})})
        if isinstance(node, Block):
            for index, child in sorted(node.children.items()):
                walk(child, [*path, index])

    # The main's horizontal block contains the chat and detail columns; keep both and their paths.
    columns = [(index, child) for index, child in app.main.children.items()
               if isinstance(child, Block) and child.type == "flex_container"
               and any(isinstance(item, Block) and item.type == "column" for item in child.children.values())]
    assert len(columns) == 1, "Main chat/detail columns must remain explicit"
    index, node = columns[0]
    walk(node, [0, index])
    return rows


def assert_snapshot(name, app, forwarded):
    actual = layout_snapshot(app, forwarded)
    expected = json.loads((SNAPSHOTS / f"{name}.json").read_text(encoding="utf-8"))
    assert actual == expected


@pytest.mark.parametrize("last_count", [4, 3])
def test_history_order_containers_html_and_widget_geometry(backend, layout_messages, monkeypatch, last_count):
    from config import settings

    monkeypatch.setattr(settings, "answer_feedback_enabled", True)
    app = page(messages=history(last_count))
