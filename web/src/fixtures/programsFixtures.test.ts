it('freezes all 75 program fixture names and original bytes', () => {
  const root = resolve('src/fixtures/programs');
  const names = [
    ...readdirSync(root).filter((n) => n.endsWith('.json')),
    ...readdirSync(root + '/expected').map((n) => 'expected/' + n),
  ].sort();
  expect(names).toEqual(Object.keys(expected).sort());
  for (const [name, hash] of Object.entries(expected))
    expect(
      createHash('sha256')
        .update(readFileSync(root + '/' + name))
        .digest('hex'),
      name,
    ).toBe(hash);
});
